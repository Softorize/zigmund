const std = @import("std");
const Response = @import("../http/response.zig").Response;

/// RFC 7807 Problem Details for HTTP APIs.
///
/// Provides a standardised way to carry machine-readable error details in an
/// HTTP response body. The Content-Type is set to `application/problem+json`
/// and the JSON payload includes the members defined in RFC 7807 Section 3.1.
pub const ProblemDetail = struct {
    /// A URI reference that identifies the problem type (default "about:blank").
    type_uri: []const u8 = "about:blank",
    /// A short, human-readable summary of the problem type.
    title: []const u8,
    /// The HTTP status code generated by the origin server for this occurrence.
    status: u16,
    /// A human-readable explanation specific to this occurrence of the problem.
    detail: ?[]const u8 = null,
    /// A URI reference that identifies the specific occurrence of the problem.
    instance: ?[]const u8 = null,
};

/// Create a `Response` from a `ProblemDetail`.
///
/// The response body is a JSON object with the RFC 7807 members (`type`,
/// `title`, `status`, and optionally `detail` / `instance`).  The
/// `Content-Type` header is set to `application/problem+json` and the HTTP
/// status code is derived from `problem.status`.
pub fn problemResponse(allocator: std.mem.Allocator, problem: ProblemDetail) !Response {
    var response = try Response.json(allocator, .{
        .type = problem.type_uri,
        .title = problem.title,
        .status = problem.status,
        .detail = problem.detail,
        .instance = problem.instance,
    });
    // Override the default application/json content-type.
    response.content_type = "application/problem+json";
    response = response.withStatus(statusFromU16(problem.status));
    return response;
}

// ----- convenience constructors -----

pub fn notFound(allocator: std.mem.Allocator, detail: ?[]const u8) !Response {
    return problemResponse(allocator, .{
        .title = "Not Found",
        .status = 404,
        .detail = detail,
    });
}

pub fn badRequest(allocator: std.mem.Allocator, detail: ?[]const u8) !Response {
    return problemResponse(allocator, .{
        .title = "Bad Request",

        .detail = detail,
    });
}

// ----- helpers -----

fn statusFromU16(code: u16) std.http.Status {
    return @enumFromInt(code);
}

// ----- unit tests -----

test "problemResponse produces correct content-type and body" {
    const alloc = std.testing.allocator;
    var res = try problemResponse(alloc, .{
        .title = "Not Found",
        .status = 404,
        .detail = "no such item",
    });
    defer res.deinit(alloc);

    try std.testing.expectEqualStrings("application/problem+json", res.content_type);
    try std.testing.expectEqual(std.http.Status.not_found, res.status);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"title\":\"Not Found\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"status\":404") != null);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"detail\":\"no such item\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"type\":\"about:blank\"") != null);
}

test "convenience notFound constructor" {
    const alloc = std.testing.allocator;
    var res = try notFound(alloc, "resource missing");
    defer res.deinit(alloc);

    try std.testing.expectEqual(std.http.Status.not_found, res.status);
    try std.testing.expectEqualStrings("application/problem+json", res.content_type);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"detail\":\"resource missing\"") != null);
}

test "convenience badRequest constructor" {
    const alloc = std.testing.allocator;
    var res = try badRequest(alloc, "invalid input");
    defer res.deinit(alloc);

    try std.testing.expectEqual(std.http.Status.bad_request, res.status);
}

test "convenience unauthorized constructor" {
    const alloc = std.testing.allocator;
    var res = try unauthorized(alloc, null);
    defer res.deinit(alloc);

    try std.testing.expectEqual(std.http.Status.unauthorized, res.status);
}

test "convenience internalServerError constructor" {
    const alloc = std.testing.allocator;
    var res = try internalServerError(alloc, "something broke");
    defer res.deinit(alloc);

    try std.testing.expectEqual(std.http.Status.internal_server_error, res.status);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"detail\":\"something broke\"") != null);
}

test "null detail and instance are serialized" {
    const alloc = std.testing.allocator;
    var res = try problemResponse(alloc, .{
        .title = "Conflict",
        .status = 409,
    });
    defer res.deinit(alloc);

    try std.testing.expectEqual(std.http.Status.conflict, res.status);
    // null fields should appear as null in JSON
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"detail\":null") != null);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"instance\":null") != null);
}

test "custom type_uri is included" {
    const alloc = std.testing.allocator;
    var res = try problemResponse(alloc, .{
        .type_uri = "https://example.com/probs/out-of-credit",
        .title = "Out of Credit",
        .status = 403,
        .detail = "Your current balance is 30, but that costs 50.",
        .instance = "/account/12345/msgs/abc",
    });
    defer res.deinit(alloc);

    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"type\":\"https://example.com/probs/out-of-credit\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, res.body, "\"instance\":\"/account/12345/msgs/abc\"") != null);
}
